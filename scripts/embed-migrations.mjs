// One-off generator: emits src/lib/db-migrations.ts with migration SQL embedded
// as strings, so the admin migrate route needs no filesystem access at runtime.
import { readFileSync, readdirSync, writeFileSync } from "fs";
import { join } from "path";

const dir = join(process.cwd(), "drizzle");
const files = readdirSync(dir).filter((f) => f.endsWith(".sql")).sort();

const entries = files.map((f) => {
  const sql = readFileSync(join(dir, f), "utf-8");
  return `  { tag: ${JSON.stringify(f.replace(/\.sql$/, ""))}, sql: ${JSON.stringify(sql)} },`;
});

const out = `/**
 * Migrations embedded at build time from ./drizzle/*.sql.
 * Generated by scripts/embed-migrations.mjs — re-run after generating a new migration.
 */
export interface EmbeddedMigration {
  tag: string;
  sql: string;
}

export const MIGRATIONS: EmbeddedMigration[] = [
${entries.join("\n")}
];
`;

writeFileSync(join(process.cwd(), "src/lib/db-migrations.ts"), out);
console.log(`Wrote ${entries.length} migrations to src/lib/db-migrations.ts`);
